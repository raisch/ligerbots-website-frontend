#!/usr/bin/env node

import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import yaml from 'yaml'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)

const projectRoot = path.resolve(__dirname, '..')
const schemaPath = path.join(projectRoot, 'schema.yaml')
const modelsDir = path.join(projectRoot, 'src', 'lib', 'server', 'models')

function toPascalCase(name) {
  return String(name)
    .split(/[_\W]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')
}

function loadSchema() {
  const raw = fs.readFileSync(schemaPath, 'utf8')
  return yaml.parse(raw)
}

function buildCollectionsIndex(schema) {
  const index = new Map()

  const collections = schema.collections || []
  for (const coll of collections) {
    index.set(coll.collection, { meta: coll, fields: [] })
  }

  const fields = schema.fields || []
  for (const field of fields) {
    const colName = field.collection
    if (!index.has(colName)) {
      index.set(colName, { meta: null, fields: [] })
    }
    index.get(colName).fields.push(field)
  }

  return index
}

function buildJoiExpression(field) {
  const { type, meta = {}, schema = {} } = field

  let expr

  switch (type) {
    case 'integer':
      expr = 'Joi.number().integer()'
      break
    case 'bigInteger':
    case 'float':
    case 'decimal':
    case 'numeric':
      expr = 'Joi.number()'
      break
    case 'uuid':
      expr = 'Joi.string().uuid()'
      break
    case 'string':
    case 'text':
      expr = 'Joi.string()'
      break
    case 'boolean':
      expr = 'Joi.boolean()'
      break
    case 'date':
    case 'timestamp':
      expr = 'Joi.date().iso()'
      break
    case 'json':
      expr = 'Joi.object()'
      break
    case 'alias':
      if ((meta.special || []).includes('m2a')) {
        expr = 'Joi.array().items(Joi.any())'
      } else {
        expr = 'Joi.any()'
      }
      break
    default:
      // Fallback based on SQL data_type when available
      if (typeof schema.data_type === 'string') {
        const dt = schema.data_type
        if (dt.includes('timestamp') || dt.includes('date')) {
          expr = 'Joi.date().iso()'
        } else if (dt.includes('boolean')) {
          expr = 'Joi.boolean()'
        } else if (dt.includes('int') || dt.includes('numeric')) {
          expr = 'Joi.number()'
        } else {
          expr = 'Joi.any()'
        }
      } else {
        expr = 'Joi.any()'
      }
      break
  }

  // Enum / select choices
  const choices =
    (meta.options && Array.isArray(meta.options.choices) && meta.options.choices) ||
    (meta.display_options && Array.isArray(meta.display_options.choices) && meta.display_options.choices) ||
    null

  if (choices && choices.length > 0) {
    const values = choices
      .map((c) => c && c.value)
      .filter((v) => v !== undefined && v !== null)

    if (values.length > 0) {
      expr += `.valid(${values.map((v) => JSON.stringify(v)).join(', ')})`
    }
  }

  // String length limits
  if ((type === 'string' || type === 'text') && typeof schema.max_length === 'number') {
    expr += `.max(${schema.max_length})`
  }

  const special = meta.special || []
  const isSystemField = special.some((s) =>
    ['date-created', 'date-updated', 'user-created', 'user-updated'].includes(s)
  )

  // Required / primary key
  const isPrimaryKey = schema.is_primary_key === true
  const isRequired = !isSystemField && (meta.required === true || isPrimaryKey)

  if (isPrimaryKey && expr.startsWith('Joi.number().integer()')) {
    expr += '.positive()'
  }

  if (isRequired) {
    expr += '.required()'
  }

  // Nullability
  const nullable = schema.is_nullable === true || meta.hidden === true
  if (nullable) {
    expr += '.allow(null)'
  }

  // Defaults – only simple primitives
  const def = schema.default_value
  if (
    def !== undefined &&
    def !== null &&
    (typeof def === 'number' ||
      typeof def === 'boolean' ||
      (typeof def === 'string' && !def.includes('(')))
  ) {
    expr += `.default(${JSON.stringify(def)})`
  }

  return expr
}

function buildModelSource(collectionName, collection) {
  const typeName = `${toPascalCase(collectionName)}ModelSchema`
  const lines = []

  lines.push(`/** @module models/${typeName.replace(/Schema$/, '')} */`)
  lines.push("import Joi from 'joi'")
  lines.push('')
  lines.push(`// Auto-generated from schema.yaml for collection: ${collectionName}`)
  lines.push(`export const ${typeName} = Joi.object({`)

  const fields = collection.fields || []
  for (const field of fields) {
    const fieldName = field.field
    if (!fieldName) continue

    // Ignore noisy / autogenerated notice fields that start with "notice-"
    if (typeof fieldName === 'string' && (fieldName.startsWith('notice-') || fieldName.startsWith('divider-'))) continue

    const expr = buildJoiExpression(field)
    lines.push(`  ${fieldName}: ${expr},`)
  }

  lines.push('})')
  lines.push('')
  lines.push(`export default ${typeName}`)
  lines.push('')

  return lines.join('\n')
}

async function main() {
  const schema = loadSchema()
  const collectionsIndex = buildCollectionsIndex(schema)

  fs.mkdirSync(modelsDir, { recursive: true })

  for (const [collectionName, collection] of collectionsIndex.entries()) {
    const src = buildModelSource(collectionName, collection)
    const targetPath = path.join(modelsDir, `${collectionName}.model.js`)
    fs.writeFileSync(targetPath, src, 'utf8')
    // eslint-disable-next-line no-console
    console.log(`Generated model: ${path.relative(projectRoot, targetPath)}`)
  }
}

main().catch((err) => {
  // eslint-disable-next-line no-console
  console.error('Error generating models from schema.yaml', err)
  process.exit(1)
})
